#!/usr/bin/env python3
"""Slice every part with a real slicer engine (PrusaSlicer CLI, the code base Bambu Studio is built
on) using a P2S-like profile, and report filament, time and the slicer's own print-stability alerts.

    python3 slice_all.py                 # all parts, writes slice-report.md (+ .json)
    python3 slice_all.py crank_head ...  # just these

This is a check, not the file you print: open the STLs (or the plate files in plates/) in Bambu
Studio with the P2S profile. Times are PrusaSlicer's estimate with Bambu-like speeds and limits;
expect Bambu Studio to differ by 10-30 %. Filament grams are reliable.
"""
import json
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from check_parts import BRIM, FINE, PARTS, part_qty, scad_values   # noqa: E402

STL = HERE / "stl"
WORK = HERE / "stl" / ".slice"
PROFILE = HERE / "p2s-check.ini"


def slicer():
    """the PrusaSlicer command line: $PRUSA_SLICER, or prusa-slicer / prusa-slicer-console on the PATH"""
    import os
    import shutil
    exe = os.environ.get("PRUSA_SLICER") or shutil.which("prusa-slicer") or shutil.which("prusa-slicer-console")
    if not exe:
        raise SystemExit("PrusaSlicer not found: install PrusaSlicer 2.7+ or set PRUSA_SLICER to its command-line program")
    return exe


def slice_one(name, walls, infill, out_dir=WORK, stl=None):
    out_dir.mkdir(parents=True, exist_ok=True)
    g = out_dir / f"{name}.gcode"
    lh = 0.16 if name in FINE else 0.2
    cmd = [slicer(), "--load", str(PROFILE), "--perimeters", str(walls), "--fill-density", f"{infill}%",
           "--layer-height", str(lh), "--brim-width", "5" if name in BRIM else "0",
           "--fill-pattern", "rectilinear" if int(infill) >= 100 else "gyroid",
           "--export-gcode", "-o", str(g), str(stl or STL / f"{name}.stl")]
    r = subprocess.run(cmd, capture_output=True, text=True)
    log = r.stdout + r.stderr
    alerts = []
    m = re.search(r"Detected print stability issues:\s*\n\s*\n?(.*?)\n(.*?)\n", log)
    if m:
        alerts = [a.strip() for a in m.group(2).split(",") if a.strip()]
    other = [ln.strip() for ln in log.splitlines() if re.search(r"(?i)warning|error|empty layer", ln)
             and "stability" not in ln]
    stats = {}
    if g.exists():
        txt = g.read_text(errors="ignore")
        tail = txt
        for key, pat in (("grams", r"total filament used \[g\] = ([\d.]+)"),
                         ("time", r"estimated printing time \(normal mode\) = (.+)")):
            mm = re.search(pat, tail)
            if mm:
                stats[key] = mm.group(1).strip()
        stats["layers"] = txt.count("\n;LAYER_CHANGE")
    return {"name": name, "ok": r.returncode == 0 and g.exists(), "layer": lh, "brim": name in BRIM,
            "alerts": alerts, "other": other, **stats}


def hours(t):
    d = {u: int(n) for n, u in re.findall(r"(\d+)([dhms])", t or "")}
    return d.get("d", 0) * 24 + d.get("h", 0) + d.get("m", 0) / 60 + d.get("s", 0) / 3600


def main():
    only = sys.argv[1:]
    V = scad_values()
    qmap = part_qty(V)
    rows = [(n, qmap.get(n, q), w, i) for n, q, w, i, _b, _t, _d in PARTS if not only or n in only]
    with ThreadPoolExecutor(2) as ex:
        res = list(ex.map(lambda r: slice_one(r[0], r[2], r[3]), rows))
    out = ["# Slicer check (PrusaSlicer engine, P2S-like profile)", "",
           "Generated by `cad/slice_all.py`. Each part sliced alone with its walls, infill and layer height;",
           "brim 5 mm where the printing guide says. Alerts are the slicer's own stability analysis.", "",
           "| Part | Qty | Layer | g each | Time each | Slicer alerts |", "|---|---|---|---|---|---|"]
    tot_g = tot_h = 0.0
    for (n, q, _w, _i), r in zip(rows, res):
        if n != "test_coupon":
            tot_g += q * float(r.get("grams", 0))
            tot_h += q * hours(r.get("time"))
        al = ", ".join(r["alerts"]) or ("FAILED" if not r["ok"] else "none")
        out.append(f"| `{n}` | {q} | {r['layer']} | {float(r.get('grams', 0)):.0f} | {r.get('time', '?')} | {al} |")
        print(f"{n:16s} {r.get('grams', '?'):>7s} g  {r.get('time', '?'):>14s}  {al}  {'; '.join(r['other'])[:200]}", flush=True)
    out += ["", f"Machine total (test coupon excluded): **{tot_g / 1000:.2f} kg**, about **{tot_h:.0f} h** of printing "
            "(PrusaSlicer's estimate with Bambu-like speeds; parts sliced one at a time, so plates of several parts save some time)."]
    if not only:
        (HERE / "slice-report.md").write_text("\n".join(out) + "\n")
        (HERE / "slice-report.json").write_text(json.dumps(res, indent=1))
    print(f"TOTAL {tot_g / 1000:.2f} kg, {tot_h:.0f} h")


if __name__ == "__main__":
    main()
